#!/usr/bin/env python3
"""Generates AppIcon.svg (vector master) and renders the macOS AppIcon set.

Usage:  pip install cairosvg && python3 make_icon.py
Writes: AppIcon.svg, ../Auracaster/Resources/Assets.xcassets/AppIcon.appiconset/*
"""
import json, math, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ICONSET = HERE.parent / 'Auracaster' / 'Resources' / 'Assets.xcassets' / 'AppIcon.appiconset'

SIZE = 1024
BODY = 824            # Apple macOS icon grid: 824 pt body on a 1024 canvas
ORIGIN = (SIZE - BODY) / 2
N = 5.0               # superellipse exponent ~ continuous-corner squircle


def squircle_path(cx, cy, r, n=N, steps=720):
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + r * math.copysign(abs(c) ** (2 / n), c)
        y = cy + r * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f'{x:.2f},{y:.2f}')
    return 'M' + ' L'.join(pts) + ' Z'


def build_svg() -> str:
    c = SIZE / 2
    body = squircle_path(c, c, BODY / 2)
    rings = [(118, 0.95, 10), (186, 0.70, 8), (262, 0.45, 6)]
    ring_svg = []
    for radius, alpha, width in rings:
        # soft glow (wide, faint) + crisp core stroke
        ring_svg.append(f'<circle cx="{c}" cy="{c}" r="{radius}" fill="none" stroke="#C4B5FD" stroke-opacity="{alpha*0.18:.3f}" stroke-width="{width*6}"/>')
        ring_svg.append(f'<circle cx="{c}" cy="{c}" r="{radius}" fill="none" stroke="#DDD6FE" stroke-opacity="{alpha*0.30:.3f}" stroke-width="{width*2.6}"/>')
        ring_svg.append(f'<circle cx="{c}" cy="{c}" r="{radius}" fill="none" stroke="#FFFFFF" stroke-opacity="{alpha:.3f}" stroke-width="{width}"/>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Auracaster app icon, vector master. Generated by make_icon.py. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#3730A3"/>
      <stop offset="0.55" stop-color="#4C1D95"/>
      <stop offset="1" stop-color="#6D28D9"/>
    </linearGradient>
    <radialGradient id="halo" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="#A78BFA" stop-opacity="0.75"/>
      <stop offset="0.45" stop-color="#8B5CF6" stop-opacity="0.35"/>
      <stop offset="1" stop-color="#7C3AED" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="core" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="0.55" stop-color="#FFFFFF"/>
      <stop offset="0.75" stop-color="#EDE9FE" stop-opacity="0.6"/>
      <stop offset="1" stop-color="#EDE9FE" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.22"/>
      <stop offset="0.45" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="clip"><path d="{body}"/></clipPath>
  </defs>
  <path d="{body}" fill="url(#bg)"/>
  <g clip-path="url(#clip)">
    <circle cx="{c}" cy="{c}" r="380" fill="url(#halo)"/>
    {''.join(ring_svg)}
    <circle cx="{c}" cy="{c}" r="88" fill="url(#core)"/>
    <circle cx="{c}" cy="{c}" r="50" fill="#FFFFFF"/>
    <path d="{body}" fill="url(#sheen)"/>
  </g>
  <path d="{body}" fill="none" stroke="#FFFFFF" stroke-opacity="0.18" stroke-width="3"/>
</svg>
'''


def main():
    import cairosvg
    svg = build_svg()
    (HERE / 'AppIcon.svg').write_text(svg)
    ICONSET.mkdir(parents=True, exist_ok=True)
    images = []
    for pt in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            px = pt * scale
            name = f'icon_{pt}x{pt}' + ('@2x' if scale == 2 else '') + '.png'
            cairosvg.svg2png(bytestring=svg.encode(), write_to=str(ICONSET / name),
                             output_width=px, output_height=px)
            images.append({'idiom': 'mac', 'size': f'{pt}x{pt}', 'scale': f'{scale}x', 'filename': name})
    (ICONSET / 'Contents.json').write_text(json.dumps(
        {'images': images, 'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n')


if __name__ == '__main__':
    main()
